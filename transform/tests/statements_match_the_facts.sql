{#
  Every number on a statement must be the number the long mart publishes.

  The statement views are generated by a macro that pivots the mart, so a mistake
  there would be silent: a column could pick up the wrong concept, or an aggregate
  could collapse two periods into one. This test unpivots the three views and
  compares them back, line by line.

  The comparison is exact rather than tolerant, because both sides are the same
  stored number, not two roundings of it.
#}

-- The refs below sit inside loops and conditionals, so dbt cannot see them on
-- its own.
-- depends_on: {{ ref('stg_tag_mappings') }}
-- depends_on: {{ ref('mart_income_statement') }}
-- depends_on: {{ ref('mart_balance_sheet') }}
-- depends_on: {{ ref('mart_cash_flow') }}

with published as (

    select cik, concept, period_kind, period_end, value
    from {{ ref('mart_financials') }}

),

{#- Each view unpivoted back to one row per line. -#}
from_statements as (

    {% for statement, model in [
        ('income_statement', 'mart_income_statement'),
        ('balance_sheet', 'mart_balance_sheet'),
        ('cash_flow', 'mart_cash_flow')
    ] %}
    {%- set concepts = [] -%}
    {%- if execute -%}
        {%- set concepts = run_query(
            "select concept from " ~ ref('stg_tag_mappings')
            ~ " where statement = '" ~ statement ~ "' group by concept order by min(position)"
        ).columns[0].values() -%}
    {%- endif -%}
    {% for concept in concepts %}
    select cik, '{{ concept }}' as concept, period_kind, period_end, {{ concept }} as value
    from {{ ref(model) }}
    where {{ concept }} is not null
    {{ "union all" if not (loop.last and statement == 'cash_flow') }}
    {%- endfor -%}
    {% endfor %}

)

select
    coalesce(published.cik, from_statements.cik) as cik,
    coalesce(published.concept, from_statements.concept) as concept,
    coalesce(published.period_end, from_statements.period_end) as period_end,
    published.value as mart_value,
    from_statements.value as statement_value
from published
full outer join from_statements
    on from_statements.cik = published.cik
    and from_statements.concept = published.concept
    and from_statements.period_kind = published.period_kind
    and from_statements.period_end = published.period_end
where published.value is distinct from from_statements.value
